// Builds src/theme/tokens.ts from docs/design/focus-tokens.json (the Focus brand pack).
// Run with `npm run theme` whenever the tokens file changes. Never edit tokens.ts by hand.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(__dirname, '..');
export const TOKENS_PATH = join(root, 'docs', 'design', 'focus-tokens.json');
export const OUT_PATH = join(root, 'src', 'theme', 'tokens.ts');

type Tokens = {
  color: { tokens: { name: string; value: { light: string; dark: string }; usage?: string }[] };
  type: {
    families: Record<string, string>;
    groups: { family: string; styles: { name: string; fontSize: string; lineHeight: string; fontWeight: number }[] }[];
  };
  spacing: { tokens: { name: string; value: string }[] };
  radius: { tokens: { name: string; value: string }[] };
};

const camel = (s: string) => s.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
const px = (v: string) => {
  const n = Number(v.replace(/px$/, ''));
  if (!Number.isFinite(n)) throw new Error(`Not a px value: ${v}`);
  return n;
};

// Expo Google Fonts names, by the first family named in the token and its weight.
const WEIGHT_NAMES: Record<number, string> = { 400: '400Regular', 500: '500Medium', 600: '600SemiBold', 700: '700Bold' };
const FAMILY_PREFIX: Record<string, string> = { Lexend: 'Lexend', 'Atkinson Hyperlegible Next': 'AtkinsonHyperlegibleNext' };
function fontName(familyCss: string, weight: number) {
  const first = familyCss.split(',')[0].trim().replace(/^"|"$/g, '');
  const prefix = FAMILY_PREFIX[first];
  const w = WEIGHT_NAMES[weight];
  if (!prefix || !w) throw new Error(`No Expo font for ${first} ${weight}`);
  return `${prefix}_${w}`;
}

export function generate(json: string): string {
  const t = JSON.parse(json) as Tokens;
  const light: Record<string, string> = {};
  const dark: Record<string, string> = {};
  for (const c of t.color.tokens) {
    light[camel(c.name)] = c.value.light;
    dark[camel(c.name)] = c.value.dark;
  }
  const type: Record<string, { fontFamily: string; fontSize: number; lineHeight: number }> = {};
  const fonts = new Set<string>();
  for (const g of t.type.groups) {
    for (const s of g.styles) {
      const fontFamily = fontName(t.type.families[g.family], s.fontWeight);
      fonts.add(fontFamily);
      type[camel(s.name)] = { fontFamily, fontSize: px(s.fontSize), lineHeight: px(s.lineHeight) };
    }
  }
  const space: Record<string, number> = {};
  for (const s of t.spacing.tokens) space[s.name.replace(/^space-/, '')] = px(s.value);
  const radius: Record<string, number> = {};
  for (const r of t.radius.tokens) radius[camel(r.name.replace(/^radius-/, ''))] = px(r.value);

  const j = (v: unknown) => JSON.stringify(v, null, 2).replace(/"([a-zA-Z_][a-zA-Z0-9_]*)":/g, '$1:').replace(/"(\d+)":/g, '$1:');
  return [
    '// GENERATED by scripts/gen-theme.ts from docs/design/focus-tokens.json. Do not edit by hand: run `npm run theme`.',
    '',
    `export const lightColors = ${j(light)} as const;`,
    '',
    `export const darkColors: { [K in keyof typeof lightColors]: string } = ${j(dark)};`,
    '',
    `/** Font files these styles need. Every one must be loaded in src/app/_layout.tsx. */`,
    `export const fontFiles = ${j([...fonts])} as const;`,
    '',
    `export const type = ${j(type)} as const;`,
    '',
    `export const space = ${j(space)} as const;`,
    '',
    `export const radius = ${j(radius)} as const;`,
    '',
  ].join('\n');
}

if (require.main === module) {
  writeFileSync(OUT_PATH, generate(readFileSync(TOKENS_PATH, 'utf8')));
  console.log(`Wrote ${OUT_PATH}`);
}
